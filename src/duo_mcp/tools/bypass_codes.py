import json
from collections.abc import Callable

from mcp.server.fastmcp import FastMCP

from ..api_client import DuoClient, DuoError
from ._common import NO_TOKEN


def register(mcp: FastMCP, client_factory: Callable[[], DuoClient | None]) -> None:

    @mcp.tool()
    async def duo_bypass_codes_create_bypass_codes_for_user(user_id: str, count: str | None = None, codes: str | None = None, reuse_count: str | None = None, valid_secs: str | None = None) -> str:
        """Create Bypass Codes for User.

        API: POST /admin/v1/users/{user_id}/bypass_codes

        Args:
            user_id: Required. Path parameter `user_id`.
            count: Optional. Number of new bypass codes to create. At most 10 codes (the default) can be created at a time. Codes will be generated randomly.
            codes: Optional. CSV string of codes to use. Mutually exclusive with count.
            reuse_count: Optional. The number of times generated bypass codes can be used. If 0, the codes will have an infinite reuse_count. Default: 1.
            valid_secs: Optional. The number of seconds generated bypass codes should be valid for. If 0 (the default) the codes will never expire.
        """
        client = client_factory()
        if client is None:
            return NO_TOKEN
        path = f"/admin/v1/users/{user_id}/bypass_codes"
        params = {"count": count, "codes": codes, "reuse_count": reuse_count, "valid_secs": valid_secs}
        try:
            result = await client.request("POST", path, params=params)
            return json.dumps(result, indent=2, default=str)
        except DuoError as e:
            return f"Error: {e}"

